#!/bin/bash
# ============================================================
# AI 资讯情报官 - 一键运行脚本
# ============================================================
# 使用方法：
#   ./run.sh              → 抓取→分析→生成文章（保存到 output/）
#   ./run.sh --publish    → 尝试自动发布到公众号
#   ./run.sh --cron       → 设置每日定时运行
# ============================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

echo "=============================================="
echo "🤖 AI 资讯情报官"
echo "=============================================="

# 检查 Python
if ! command -v python3 &> /dev/null; then
    echo "❌ 未找到 python3，请先安装 Python"
    exit 1
fi

# 检查配置文件中的 API Key
MODE="手动发布模式（生成文章到 output/ 目录）"
if [[ "$1" == "--publish" ]]; then
    MODE="自动发布模式（会尝试发到公众号）"
fi

echo "📋 模式: $MODE"
echo ""

# 执行主流程
python3 main.py "$@"

echo ""
echo "=============================================="
echo "✅ 执行完毕"
echo "📄 生成的文章在 output/ 目录下"
echo "=============================================="
